export function addFinanceEarningContracts({schemas,ref,operation,paths,id,instant,decimal}){
 const object=properties=>({type:'object',additionalProperties:false,properties,required:Object.keys(properties)});
 const day={type:'string',format:'date'};
 schemas.EarnedPremiumMonth=object({componentId:id,obligationId:id,transactionId:id,policyId:id,
  monthStart:day,savedMonthPremium:decimal,periodEarnedPremium:decimal,sourcePostedAt:instant});
 schemas.EarnedPremiumReview=object({agencyId:id,periodId:id,from:day,to:day,
  periodState:{enum:['open','closed']},asOf:instant,
  basis:{const:'posted-premium-component/monthly-utc-overlap-v1'},currency:{const:'GBP'},
  earnedPremium:decimal,componentCount:{type:'integer',minimum:0},
  items:{type:'array',items:ref('EarnedPremiumMonth')}});
 operation('get','/finance/agencies/{agencyId}/earned-premium','getEarnedPremium',
  'current internal finance-read and selected saved agency scope',{
   output:ref('EarnedPremiumReview'),query:[['periodId',id]]});
 const operationSchema=paths['/finance/agencies/{agencyId}/earned-premium'].get;
 operationSchema.parameters.find(parameter=>parameter.name==='periodId').required=true;
 operationSchema.responses['409']=operationSchema.responses['400'];
 const response=operationSchema.responses['200'];
 response.headers={...response.headers,'Cache-Control':{schema:{type:'string',const:'no-store'}}};
 delete response.headers.ETag;
 operationSchema['x-runtime-status']='phase-10-17-implemented';
}

