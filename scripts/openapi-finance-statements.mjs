export function addFinanceStatementContracts({schemas,ref,operation,paths,id,instant,date,decimal}) {
 const nullable=schema=>({anyOf:[schema,{type:'null'}]});
 schemas.FinanceStatementLine={type:'object',additionalProperties:false,properties:{
  sourceKey:{type:'string'},postingDate:date,debit:decimal,credit:decimal,runningBalance:decimal,
  dueDate:nullable(date),overdue:{type:'boolean'}},required:['sourceKey','postingDate','debit','credit','runningBalance','dueDate','overdue']};
 schemas.FinanceStatementSource={type:'object',additionalProperties:false,properties:{
  sourceKey:{type:'string'},sourceKind:{type:'string'},policyId:nullable(id),transactionId:nullable(id),agencyTermsVersionId:nullable(id),
  postingDate:date,postedAt:instant,effectiveAt:instant,delta:decimal,dueDate:nullable(date),
  ageDaysAtEnd:nullable({type:'integer'}),pastDueAtEnd:{type:'boolean'}},
  required:['sourceKey','sourceKind','policyId','transactionId','agencyTermsVersionId','postingDate','postedAt','effectiveAt','delta','dueDate','ageDaysAtEnd','pastDueAtEnd']};
 const base={id,agencyId:id,version:{type:'integer',minimum:1},from:date,to:date,sourceCutoff:instant,
  opening:decimal,debits:decimal,credits:decimal,closing:decimal,createdAt:instant};
 schemas.FinanceStatementView={type:'object',additionalProperties:false,properties:{...base,rows:{type:'array',items:ref('FinanceStatementLine')},
  sources:{type:'array',items:ref('FinanceStatementSource')},sourceHash:{type:'string',pattern:'^[0-9A-F]{64}$'},contentHash:{type:'string',pattern:'^[0-9A-F]{64}$'}},
  required:[...Object.keys(base),'rows','sources','sourceHash','contentHash']};
 const listItem={...base};delete listItem.agencyId;
 schemas.FinanceStatementListItem={type:'object',additionalProperties:false,properties:listItem,required:Object.keys(listItem)};
 schemas.FinanceStatementPage={type:'object',additionalProperties:false,properties:{page:{type:'integer',minimum:1},pageSize:{type:'integer',minimum:1,maximum:100},
  total:{type:'integer',minimum:0},items:{type:'array',items:ref('FinanceStatementListItem')}},required:['page','pageSize','total','items']};
 schemas.FinanceStatementGeneration={type:'object',additionalProperties:false,properties:{id,version:{type:'integer',minimum:1}},required:['id','version']};
 operation('post','/finance/agencies/{agencyId}/statements','generateFinanceStatement','statement-generate and current agency scope',{
  input:{type:'object',additionalProperties:false,properties:{from:date,to:date},required:['from','to']},
  output:ref('FinanceStatementGeneration'),status:201});
 operation('get','/finance/agencies/{agencyId}/statements','listFinanceStatements','finance-read or own agency statement-download grant',{
  output:ref('FinanceStatementPage'),query:[['page',{type:'integer',minimum:1}],['pageSize',{type:'integer',minimum:1,maximum:100}]]});
 operation('get','/finance/statements/{id}','getFinanceStatement','finance-read or own agency statement-download grant',{
  output:ref('FinanceStatementView')});
 operation('get','/finance/statements/{id}/download','downloadFinanceStatement','finance-read or own agency statement-download grant');
 const download=paths['/finance/statements/{id}/download'].get.responses['200'];
 download.content={'text/csv':{schema:{type:'string',format:'binary'}}};
 download.headers={'Content-Disposition':{description:'Exact saved statement version filename.',schema:{type:'string'}},
  'ETag':{description:'SHA-256 of saved bytes.',schema:{type:'string'}},
  'Cache-Control':{description:'Finance data is not cacheable.',schema:{type:'string',const:'no-store'}}};
 for(const path of ['/finance/agencies/{agencyId}/statements','/finance/statements/{id}']) {
  for(const [method,op] of Object.entries(paths[path])) {
   const success=op.responses[method==='post'?'201':'200'];
   if(success)success.headers={...success.headers,'Cache-Control':{schema:{type:'string',const:'no-store'}}};
   op['x-runtime-status']='phase-10-03-implemented';
  }
 }
 paths['/finance/statements/{id}/download'].get['x-runtime-status']='phase-10-03-implemented';
}

