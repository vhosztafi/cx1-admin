export function addFinancePaymentContracts({schemas,ref,operation,paths,id,instant,decimal}) {
 const nullable=schema=>({anyOf:[schema,{type:'null'}]});
 schemas.FinancePayment={type:'object',additionalProperties:false,properties:{
  id,refundRequestId:id,agencyId:id,creditObligationId:id,debtorKind:{enum:['agency','relationship']},
  debtorId:id,amount:decimal,currency:{const:'GBP'},workId:id,
  state:{enum:['queued','uncertain','provider-acknowledged/application-pending','paid','rejected','failed']},
  providerState:nullable({enum:['accepted','rejected']}),providerOperationId:nullable(id),
  appliedAt:nullable(instant),priorPaymentId:nullable(id),reviewReason:{type:'string'},etag:{type:'string'}
 },required:['id','refundRequestId','agencyId','creditObligationId','debtorKind','debtorId','amount',
  'currency','workId','state','providerState','providerOperationId','appliedAt','priorPaymentId',
  'reviewReason','etag']};
 schemas.FinancePaymentQueued={type:'object',additionalProperties:false,properties:{
  paymentId:id,refundId:id,state:{const:'queued'}
 },required:['paymentId','refundId','state']};
 operation('post','/finance/refunds/{id}/payments','queueFinanceRefundPayment',
  'finance-payment-execute and current internal finance identity/agency scope',{
   status:202,existing:true,input:{type:'object',additionalProperties:false,
    properties:{reason:{type:'string',minLength:10,maxLength:1000},priorPaymentId:id},required:['reason']},
   output:ref('FinancePaymentQueued')});
 operation('get','/finance/payments/{id}','getFinanceRefundPayment',
  'finance-read and current internal finance identity/agency scope',{output:ref('FinancePayment')});
 operation('post','/finance/payments/{id}/resume','resumeFinanceRefundPayment',
  'finance-payment-execute and current internal finance identity/agency scope',{
   status:202,existing:true,input:{type:'object',additionalProperties:false,
    properties:{reason:{type:'string',minLength:10,maxLength:1000}},required:['reason']},
   output:ref('FinancePaymentQueued')});
 for(const path of ['/finance/refunds/{id}/payments','/finance/payments/{id}',
  '/finance/payments/{id}/resume'])
  for(const op of Object.values(paths[path]))op['x-runtime-status']='phase-10-08-implemented';
}

export async function writeFinancePaymentTypes() {
 const {mkdir,writeFile}=await import('node:fs/promises');
 await mkdir('contracts/generated',{recursive:true});
 await writeFile('contracts/generated/finance-payments.ts',`// Generated by scripts/openapi-finance-payments.mjs.
export type FinancePayment = { id: string; refundRequestId: string; agencyId: string;
  creditObligationId: string; debtorKind: 'agency' | 'relationship'; debtorId: string;
  amount: string; currency: 'GBP'; workId: string;
  state: 'queued' | 'uncertain' | 'provider-acknowledged/application-pending' | 'paid' | 'rejected' | 'failed';
  providerState: 'accepted' | 'rejected' | null; providerOperationId: string | null;
  appliedAt: string | null; priorPaymentId: string | null; reviewReason: string; etag: string };
export type FinancePaymentQueued = { paymentId: string; refundId: string; state: 'queued' };
`);
}
