export function addFinancePeriodContracts({schemas,ref,operation,paths,id,instant,decimal}) {
 const nullable=schema=>({anyOf:[schema,{type:'null'}]});
 const day={type:'string',format:'date'};
 schemas.FinancePeriodReview={type:'object',additionalProperties:false,properties:{
  id,from:day,to:day,state:{enum:['open','closed']},blockers:{type:'array',items:{type:'string'}},
  closedAt:nullable(instant),closedBy:nullable(id),closeReason:nullable({type:'string'}),
  sourceCutoff:nullable(instant),closeChecklistJson:nullable({type:'string'}),etag:{type:'string'}
 },required:['id','from','to','state','blockers','closedAt','closedBy','closeReason','sourceCutoff','closeChecklistJson','etag']};
 schemas.FinancePeriodClosed={type:'object',additionalProperties:false,properties:{
  periodId:id,state:{const:'closed'},closedAt:instant
 },required:['periodId','state','closedAt']};
 schemas.FinanceCorrection={type:'object',additionalProperties:false,properties:{
  id,originalSourceId:id,originalSourceKind:{enum:['insurance','finance-posting']},postingId:id,
  agencyId:id,postingDate:day,effectiveAt:instant,debtorDelta:decimal,providerDelta:decimal,
  cashDelta:decimal,internalDelta:decimal,reason:{type:'string'}
 },required:['id','originalSourceId','originalSourceKind','postingId','agencyId','postingDate',
  'effectiveAt','debtorDelta','providerDelta','cashDelta','internalDelta','reason']};
 schemas.FinanceCorrectionPosted={type:'object',additionalProperties:false,properties:{
  id,postingId:id,accountingPeriodId:id,postingDate:day
 },required:['id','postingId','accountingPeriodId','postingDate']};
 operation('get','/finance/periods','listFinancePeriods',
  'finance-read and current internal finance identity',{
   output:{type:'array',items:ref('FinancePeriodReview')}});
 operation('get','/finance/periods/{periodId}','getFinancePeriod',
  'finance-read and current internal finance identity',{output:ref('FinancePeriodReview')});
 operation('post','/finance/periods/{periodId}/close','closeFinancePeriod',
  'finance-period-close and current internal finance identity',{
   existing:true,input:{type:'object',additionalProperties:false,properties:{
    reason:{type:'string',minLength:10,maxLength:1000}},required:['reason']},
   output:ref('FinancePeriodClosed')});
 operation('post','/finance/corrections','postFinanceCorrection',
  'finance-correction-post and current internal finance/agency scope',{
   status:201,input:{type:'object',additionalProperties:false,properties:{
    originalSourceKind:{enum:['insurance','finance-posting']},originalSourceId:id,
    debtorDelta:decimal,providerDelta:decimal,cashDelta:decimal,internalDelta:decimal,
    effectiveAt:instant,reason:{type:'string',minLength:10,maxLength:1000}
   },required:['originalSourceKind','originalSourceId','debtorDelta','providerDelta','cashDelta',
    'internalDelta','effectiveAt','reason']},output:ref('FinanceCorrectionPosted')});
 operation('post','/finance/journals','postFinanceJournalCorrection',
  'finance-correction-post and current internal finance/agency scope',{
   status:201,input:paths['/finance/corrections'].post.requestBody.content['application/json'].schema,
   output:ref('FinanceCorrectionPosted')});
 operation('get','/finance/corrections/{id}','getFinanceCorrection',
  'finance-read and current internal finance/agency scope',{output:ref('FinanceCorrection')});
 for(const path of ['/finance/periods','/finance/periods/{periodId}','/finance/periods/{periodId}/close',
  '/finance/corrections','/finance/journals','/finance/corrections/{id}'])
  for(const op of Object.values(paths[path]))op['x-runtime-status']='phase-10-11-implemented';
}

