export function addFinanceSubmissionContracts({schemas,ref,operation,paths,id,instant}) {
 const nullable=schema=>({anyOf:[schema,{type:'null'}]});
 const hash={type:'string',pattern:'^[0-9A-Fa-f]{64}$'};
 schemas.FinanceSubmissionAttempt={type:'object',additionalProperties:false,properties:{
  attempt:{type:'integer',minimum:1},outcome:{type:'string'},errorCode:nullable({type:'string'}),
  startedAt:instant,endedAt:nullable(instant)
 },required:['attempt','outcome','errorCode','startedAt','endedAt']};
 schemas.FinanceSubmission={type:'object',additionalProperties:false,properties:{
  id,batchId:id,versionId:id,contentHash:hash,workId:id,
  state:{enum:['queued','uncertain','submitted','rejected','failed']},
  providerState:nullable({enum:['accepted','rejected']}),providerOperationId:nullable(id),
  providerEventId:nullable({type:'string'}),appliedAt:nullable(instant),
  attempts:{type:'array',items:ref('FinanceSubmissionAttempt')}
 },required:['id','batchId','versionId','contentHash','workId','state','providerState',
  'providerOperationId','providerEventId','appliedAt','attempts']};
 schemas.FinanceSubmissionQueued={type:'object',additionalProperties:false,properties:{
  submissionId:id,batchId:id,versionId:id,state:{const:'queued'}
 },required:['submissionId','batchId','versionId','state']};
 const access='finance-bordereau and current internal finance identity/provider scope';
 operation('post','/finance/bordereaux/{batchId}/versions/{versionId}/submissions',
  'queueFinanceBordereauSubmission',access,{status:202,existing:true,
   input:{type:'object',additionalProperties:false,properties:{contentHash:hash},required:['contentHash']},
   output:ref('FinanceSubmissionQueued')});
 operation('get','/finance/bordereaux/{batchId}/versions/{versionId}/submission',
  'getFinanceBordereauSubmission',access,{output:ref('FinanceSubmission')});
 for(const path of ['/finance/bordereaux/{batchId}/versions/{versionId}/submissions',
  '/finance/bordereaux/{batchId}/versions/{versionId}/submission'])
  for(const op of Object.values(paths[path]))op['x-runtime-status']='phase-10-10-implemented';
}

