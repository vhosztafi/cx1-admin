export function addFinanceLedgerContracts({schemas,ref,operation,paths,id,instant,date,decimal}) {
 const nullable=schema=>({anyOf:[schema,{type:'null'}]});
 const positive={type:'integer',minimum:1};
 const row={type:'object',additionalProperties:false,properties:{
  sourceKey:{type:'string',minLength:11,maxLength:80},sourceKind:{type:'string',minLength:1,maxLength:30},movementKind:{type:'string',minLength:1,maxLength:30},
  agencyId:id,relationshipId:nullable(id),policyId:nullable(id),transactionId:nullable(id),
  effectiveAt:instant,postingDate:date,postedAt:instant,debtorKind:{type:'string',enum:['agency','relationship']},
  debtorId:nullable(id),debtorDelta:decimal,providerDelta:decimal,currency:{const:'GBP'},
  dueDate:nullable(date),status:{type:'string',enum:['outstanding','credit','no-balance','posted']},accountingPeriodId:nullable(id),
  grossDue:nullable(decimal),tax:nullable(decimal),fee:nullable(decimal),commission:nullable(decimal),netDue:nullable(decimal)
 }};
 row.required=Object.keys(row.properties);
 schemas.FinanceLedgerRow=row;
 schemas.FinanceLedgerPage={type:'object',additionalProperties:false,properties:{page:positive,pageSize:positive,total:{type:'integer',minimum:0},items:{type:'array',items:ref('FinanceLedgerRow')}},required:['page','pageSize','total','items']};
 schemas.FinanceAccountSummary={type:'object',additionalProperties:false,properties:{agencyId:id,relationshipId:nullable(id),movementCount:{type:'integer',minimum:0},agencyReceivable:decimal,relationshipReceivable:decimal,providerPayable:decimal,currency:{const:'GBP'}},required:['agencyId','relationshipId','movementCount','agencyReceivable','relationshipReceivable','providerPayable','currency']};
 schemas.FinanceTransactionDetail={type:'object',additionalProperties:false,properties:{transactionId:id,policyId:id,agencyId:id,relationshipId:id,obligationId:id,journalId:id,accountingPeriodId:nullable(id),postingDate:date,postedAt:instant,effectiveAt:instant,agencyTermsVersionId:id,debtorKind:{type:'string',enum:['agency','relationship']},settlement:{type:'string',enum:['net-remittance','separate-payment']},invoiceDue:decimal,brokerPayable:decimal,termsSnapshotJson:{type:'string'},movement:ref('FinanceLedgerRow')}};
 schemas.FinanceTransactionDetail.required=Object.keys(schemas.FinanceTransactionDetail.properties);
 const get=(path,name,permission,output,query=[])=>{
  delete paths[path]?.get;
  operation('get',path,name,permission,{output:ref(output),query});
  paths[path].get['x-runtime-status']='phase-10-02-implemented';
  paths[path].get.description+=' Current stored actor and selected agency/relationship or policy ownership are checked inside the read transaction. Amounts are exact decimal strings. No cash status is inferred from insurance posting.';
  // Generic error responses are shared objects in the generator; only mutate
  // this route's success response, never the global error contract.
  const success=paths[path].get.responses['200'];
  success.headers={...success.headers,'Cache-Control':{schema:{type:'string',const:'no-store'},description:'Finance data is not cacheable.'}};
 };
 get('/finance/ledger','listFinanceLedger','finance-read','FinanceLedgerPage',[
  ['agencyId',id],['relationshipId',id],['from',date],['to',date],['page',positive],['pageSize',{type:'integer',minimum:1,maximum:100}]]);
 paths['/finance/ledger'].get.parameters.find(x=>x.name==='agencyId').required=true;
 get('/finance/accounts/{agencyId}','getFinanceAccount','finance-read','FinanceAccountSummary',[['relationshipId',id]]);
 get('/finance/transactions/{transactionId}','getFinanceTransaction','finance-read','FinanceTransactionDetail');
 get('/policies/{policyId}/finance','getPolicyFinance','finance-read or current policy-read','FinanceLedgerPage');
}

